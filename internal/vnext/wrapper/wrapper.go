// Package wrapper generates the non-customizable relkitw entrypoints used by
// product repositories.
package wrapper

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/shichao402/relkit/internal/fsx"
	"github.com/shichao402/relkit/internal/vnext/project"
)

type Options struct {
	ProjectPath string
	OutputDir   string
}

func Generate(options Options) ([]string, error) {
	projectPath := options.ProjectPath
	if projectPath == "" {
		projectPath = "relkit.project.json"
	}
	product, err := project.Load(projectPath)
	if err != nil {
		return nil, err
	}
	outputDir := options.OutputDir
	if outputDir == "" {
		outputDir = filepath.Dir(projectPath)
	}
	projectName, err := filepath.Rel(outputDir, projectPath)
	if err != nil {
		return nil, err
	}
	projectName = filepath.ToSlash(projectName)
	if strings.HasPrefix(projectName, "../") {
		return nil, fmt.Errorf("project file must be inside wrapper output directory")
	}
	shellPath := filepath.Join(outputDir, "relkitw")
	cmdPath := filepath.Join(outputDir, "relkitw.cmd")
	operatorHash := operatorRefHash(product.OperatorRef)
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return nil, err
	}
	if err := writeAtomic(shellPath, []byte(shellScript(projectName, product.TrustFingerprint, operatorHash)), 0o755); err != nil {
		return nil, err
	}
	if err := writeAtomic(cmdPath, []byte(cmdScript(filepath.FromSlash(projectName), product.TrustFingerprint, operatorHash)), 0o644); err != nil {
		return nil, err
	}
	return []string{shellPath, cmdPath}, nil
}

func shellScript(projectPath, fingerprint, operatorHash string) string {
	return fmt.Sprintf(`#!/bin/sh
# Generated by Relkit. Do not customize; regenerate from relkit.project.json.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT="$ROOT/%s"
RESOLUTION="$ROOT/.relkit/resolution.json"
CANDIDATE="${RELKIT_CANDIDATE_DIGEST:-}"
if [ -n "$CANDIDATE" ]; then
  RESOLUTION="$ROOT/.relkit/candidate/resolution.json"
fi
EXPECTED_ROOT="%s"
OPERATOR_HASH="%s"

if [ -n "${RELKIT_BOOTSTRAP_CLI:-}" ]; then
  BOOTSTRAP="$RELKIT_BOOTSTRAP_CLI"
elif [ -x "$ROOT/.relkit/bootstrap/relkit" ]; then
  BOOTSTRAP="$ROOT/.relkit/bootstrap/relkit"
elif [ -n "${RELKIT_HOME:-}" ]; then
  case "$(uname -s)-$(uname -m)" in
    Darwin-arm64) TARGET=darwin-arm64 ;;
    Darwin-x86_64) TARGET=darwin-amd64 ;;
    Linux-x86_64) TARGET=linux-amd64 ;;
    Linux-aarch64|Linux-arm64) TARGET=linux-arm64 ;;
    *) echo "relkitw: unsupported bootstrap platform $(uname -s)/$(uname -m)" >&2; exit 2 ;;
  esac
  BOOTSTRAP="$RELKIT_HOME/operators/$OPERATOR_HASH/bootstrap/$TARGET/relkit"
elif [ "$(uname -s)" = "Darwin" ]; then
  case "$(uname -m)" in arm64) TARGET=darwin-arm64 ;; x86_64) TARGET=darwin-amd64 ;; *) TARGET=unsupported ;; esac
  BOOTSTRAP="$HOME/Library/Application Support/relkit/operators/$OPERATOR_HASH/bootstrap/$TARGET/relkit"
else
  case "$(uname -m)" in x86_64) TARGET=linux-amd64 ;; aarch64|arm64) TARGET=linux-arm64 ;; *) TARGET=unsupported ;; esac
  BOOTSTRAP="${XDG_CONFIG_HOME:-$HOME/.config}/relkit/operators/$OPERATOR_HASH/bootstrap/$TARGET/relkit"
fi

if [ ! -x "${BOOTSTRAP:-}" ]; then
  if [ -n "${RELKIT_BOOTSTRAP_URL:-}" ] && [ -n "${RELKIT_BOOTSTRAP_SHA256:-}" ]; then
    mkdir -p "$(dirname "$BOOTSTRAP")"
    TMP="$BOOTSTRAP.tmp.$$"
    trap 'rm -f "$TMP"' EXIT HUP INT TERM
    curl --fail --location --silent --show-error "$RELKIT_BOOTSTRAP_URL" --output "$TMP"
    if command -v sha256sum >/dev/null 2>&1; then
      ACTUAL=$(sha256sum "$TMP" | awk '{print $1}')
    elif command -v shasum >/dev/null 2>&1; then
      ACTUAL=$(shasum -a 256 "$TMP" | awk '{print $1}')
    else
      echo "relkitw: no SHA-256 verifier (sha256sum or shasum)" >&2
      exit 2
    fi
    if [ "$ACTUAL" != "$RELKIT_BOOTSTRAP_SHA256" ]; then
      echo "relkitw: bootstrap SHA-256 mismatch" >&2
      exit 2
    fi
    chmod 755 "$TMP"
    mv "$TMP" "$BOOTSTRAP"
    trap - EXIT HUP INT TERM
  elif command -v relkit >/dev/null 2>&1; then
    BOOTSTRAP=$(command -v relkit)
  fi
fi
if [ ! -x "${BOOTSTRAP:-}" ]; then
  echo "relkitw: no bootstrap CLI; set RELKIT_BOOTSTRAP_CLI or provision .relkit/bootstrap/relkit" >&2
  exit 2
fi

export RELKIT_EXPECTED_ROOT_FINGERPRINT="$EXPECTED_ROOT"
export RELKIT_PROJECT="$PROJECT"
if [ "${RELKIT_REFRESH_RESOLUTION:-0}" = "1" ]; then
  if [ -n "$CANDIDATE" ]; then
    "$BOOTSTRAP" resolve --project "$PROJECT" --out "$RESOLUTION" --candidate "$CANDIDATE" --replace
  else
    "$BOOTSTRAP" resolve --project "$PROJECT" --out "$RESOLUTION" --replace
  fi
elif [ -n "$CANDIDATE" ]; then
  # Always ask resolve to prove that an existing immutable candidate file
  # selects the requested digest; Resolve reuses it without selecting again.
  "$BOOTSTRAP" resolve --project "$PROJECT" --out "$RESOLUTION" --candidate "$CANDIDATE"
elif [ ! -f "$RESOLUTION" ]; then
    "$BOOTSTRAP" resolve --project "$PROJECT" --out "$RESOLUTION"
fi
"$BOOTSTRAP" doctor --resolution "$RESOLUTION" --project "$PROJECT"
"$BOOTSTRAP" materialize --resolution "$RESOLUTION" --project-root "$ROOT"
export RELKIT_RESOLUTION="$RESOLUTION"
cd "$ROOT"
GO_MODFILE="$ROOT/.relkit/components/sdk/go/relkit.mod"
if [ -f "$GO_MODFILE" ]; then
  export GOFLAGS="-modfile=.relkit/components/sdk/go/relkit.mod ${GOFLAGS:-}"
fi
SELECTED="$ROOT/.relkit/components/bin/relkit"
if [ ! -x "$SELECTED" ]; then
  echo "relkitw: selected CLI was not materialized at $SELECTED" >&2
  exit 2
fi
export RELKIT_CORE="$SELECTED"
exec "$SELECTED" "$@"
`, projectPath, fingerprint, operatorHash)
}

func cmdScript(projectPath, fingerprint, operatorHash string) string {
	return fmt.Sprintf(`@echo off
REM Generated by Relkit. Do not customize; regenerate from relkit.project.json.
setlocal
set "ROOT=%%~dp0"
set "PROJECT=%%ROOT%%%s"
set "RESOLUTION=%%ROOT%%.relkit\resolution.json"
set "CANDIDATE=%%RELKIT_CANDIDATE_DIGEST%%"
if not "%%CANDIDATE%%"=="" set "RESOLUTION=%%ROOT%%.relkit\candidate\resolution.json"
set "RELKIT_EXPECTED_ROOT_FINGERPRINT=%s"
set "RELKIT_PROJECT=%%PROJECT%%"
set "OPERATOR_HASH=%s"

if not "%%RELKIT_BOOTSTRAP_CLI%%"=="" (
  set "BOOTSTRAP=%%RELKIT_BOOTSTRAP_CLI%%"
) else if exist "%%ROOT%%.relkit\bootstrap\relkit.exe" (
  set "BOOTSTRAP=%%ROOT%%.relkit\bootstrap\relkit.exe"
) else if not "%%RELKIT_HOME%%"=="" (
  set "BOOTSTRAP=%%RELKIT_HOME%%\operators\%%OPERATOR_HASH%%\bootstrap\windows-amd64\relkit.exe"
) else if not "%%APPDATA%%"=="" (
  set "BOOTSTRAP=%%APPDATA%%\relkit\operators\%%OPERATOR_HASH%%\bootstrap\windows-amd64\relkit.exe"
) else (
  for /f "delims=" %%%%I in ('where relkit.exe 2^>nul') do if not defined BOOTSTRAP set "BOOTSTRAP=%%%%I"
)
if not exist "%%BOOTSTRAP%%" if not "%%RELKIT_BOOTSTRAP_URL%%"=="" if not "%%RELKIT_BOOTSTRAP_SHA256%%"=="" (
  for %%%%I in ("%%BOOTSTRAP%%") do if not exist "%%%%~dpI" mkdir "%%%%~dpI"
  powershell.exe -NoProfile -NonInteractive -Command "$ProgressPreference='SilentlyContinue'; Invoke-WebRequest -UseBasicParsing -Uri $env:RELKIT_BOOTSTRAP_URL -OutFile ($env:BOOTSTRAP + '.tmp'); if ((Get-FileHash -Algorithm SHA256 ($env:BOOTSTRAP + '.tmp')).Hash.ToLowerInvariant() -ne $env:RELKIT_BOOTSTRAP_SHA256.ToLowerInvariant()) { Remove-Item ($env:BOOTSTRAP + '.tmp') -Force; exit 3 }; Move-Item ($env:BOOTSTRAP + '.tmp') $env:BOOTSTRAP -Force" || exit /b %%errorlevel%%
)
if not exist "%%BOOTSTRAP%%" (
  for /f "delims=" %%%%I in ('where relkit.exe 2^>nul') do if not exist "%%BOOTSTRAP%%" set "BOOTSTRAP=%%%%I"
)
if not exist "%%BOOTSTRAP%%" (
  echo relkitw: no bootstrap CLI; set RELKIT_BOOTSTRAP_CLI or provision .relkit\bootstrap\relkit.exe 1>&2
  exit /b 2
)

if "%%RELKIT_REFRESH_RESOLUTION%%"=="1" if "%%CANDIDATE%%"=="" "%%BOOTSTRAP%%" resolve --project "%%PROJECT%%" --out "%%RESOLUTION%%" --replace || exit /b %%errorlevel%%
if "%%RELKIT_REFRESH_RESOLUTION%%"=="1" if not "%%CANDIDATE%%"=="" "%%BOOTSTRAP%%" resolve --project "%%PROJECT%%" --out "%%RESOLUTION%%" --candidate "%%CANDIDATE%%" --replace || exit /b %%errorlevel%%
if not "%%RELKIT_REFRESH_RESOLUTION%%"=="1" if not "%%CANDIDATE%%"=="" "%%BOOTSTRAP%%" resolve --project "%%PROJECT%%" --out "%%RESOLUTION%%" --candidate "%%CANDIDATE%%" || exit /b %%errorlevel%%
if not "%%RELKIT_REFRESH_RESOLUTION%%"=="1" if "%%CANDIDATE%%"=="" if not exist "%%RESOLUTION%%" "%%BOOTSTRAP%%" resolve --project "%%PROJECT%%" --out "%%RESOLUTION%%" || exit /b %%errorlevel%%
"%%BOOTSTRAP%%" doctor --resolution "%%RESOLUTION%%" --project "%%PROJECT%%" || exit /b %%errorlevel%%
"%%BOOTSTRAP%%" materialize --resolution "%%RESOLUTION%%" --project-root "%%ROOT%%" || exit /b %%errorlevel%%
set "RELKIT_RESOLUTION=%%RESOLUTION%%"
cd /d "%%ROOT%%" || exit /b %%errorlevel%%
set "GO_MODFILE=%%ROOT%%.relkit\components\sdk\go\relkit.mod"
if exist "%%GO_MODFILE%%" set "GOFLAGS=-modfile=.relkit\components\sdk\go\relkit.mod %%GOFLAGS%%"
set "SELECTED=%%ROOT%%.relkit\components\bin\relkit.exe"
if not exist "%%SELECTED%%" (
  echo relkitw: selected CLI was not materialized at %%SELECTED%% 1>&2
  exit /b 2
)
set "RELKIT_CORE=%%SELECTED%%"
"%%SELECTED%%" %%*
exit /b %%errorlevel%%
`, projectPath, fingerprint, operatorHash)
}

func operatorRefHash(value string) string {
	sum := sha256.Sum256([]byte(value))
	return hex.EncodeToString(sum[:])
}

func writeAtomic(path string, data []byte, mode os.FileMode) error {
	temporary := path + ".tmp"
	if err := os.WriteFile(temporary, data, mode); err != nil {
		return err
	}
	if err := os.Chmod(temporary, mode); err != nil {
		_ = os.Remove(temporary)
		return err
	}
	if err := fsx.Replace(temporary, path); err != nil {
		_ = os.Remove(temporary)
		return err
	}
	return nil
}
